def build_disease_card(
    disease: str,
    training_frame: pd.DataFrame,
    symptom_columns: list[str],
    language: str = "tr",
) -> dict[str, Any]:
    """Build a structured info card for a disease from data and curated text."""

    disease_rows = training_frame[training_frame[TARGET_COLUMN] == disease]
    total = len(training_frame)
    count = len(disease_rows)
    prevalence_pct = round((count / total) * 100, 2) if total else 0.0

    symptom_freq: list[tuple[str, float]] = []
    if not disease_rows.empty:
        for symptom in symptom_columns:
            freq = float(disease_rows[symptom].mean())
            if freq > 0:
                symptom_freq.append((symptom, freq))
        symptom_freq.sort(key=lambda item: item[1], reverse=True)

    top_symptoms = [
        display_symptom_name(symptom, language)
        for symptom, _ in symptom_freq[:8]
    ]

    summary_entry = DISEASE_SUMMARIES.get(disease, {})
    summary = summary_entry.get(language) or summary_entry.get("tr") or (
        f"{humanize_label(disease)} hakkında veri setinde {count} kayıt bulunmaktadır."
        if language == "tr"
        else f"The dataset contains {count} records for {humanize_label(disease)}."
    )

    return {
        "name": humanize_label(disease),
        "raw_name": disease,
        "summary": summary,
        "prevalence_pct": prevalence_pct,
        "record_count": count,
        "top_symptoms": top_symptoms,
        "when_to_see_doctor": WHEN_TO_SEE_DOCTOR.get(language, WHEN_TO_SEE_DOCTOR["tr"]),
    }


def list_all_diseases(training_frame: pd.DataFrame) -> list[str]:
    """Return sorted unique disease labels from the training frame."""

    return sorted(training_frame[TARGET_COLUMN].astype(str).unique())


